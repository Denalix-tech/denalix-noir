/**
 * Date formatting shared by blog and admin surfaces.
 *
 * A fixed UTC timezone keeps server and client output identical, avoiding
 * hydration mismatches on dates rendered in both places.
 */

const POST_DATE = new Intl.DateTimeFormat("en-US", {
  year: "numeric",
  month: "long",
  day: "numeric",
  timeZone: "UTC",
});

const ADMIN_DATE_TIME = new Intl.DateTimeFormat("en-US", {
  year: "numeric",
  month: "short",
  day: "numeric",
  hour: "numeric",
  minute: "2-digit",
  timeZone: "UTC",
});

export function formatPostDate(value: string | null | undefined): string | null {
  if (!value) return null;
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return null;
  return POST_DATE.format(date);
}

export function formatAdminDateTime(value: string | null | undefined): string {
  if (!value) return "—";
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return "—";
  return `${ADMIN_DATE_TIME.format(date)} UTC`;
}
